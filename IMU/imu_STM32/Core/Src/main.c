    sprintf(uart_buf, "%d,%d,%d,%d,%d,%d,%d\r\n", accel_x, accel_y, accel_z, raw_temp, gyro_x, gyro_y, gyro_z);
    HAL_UART_Transmit(&huart2, (uint8_t *)uart_buf, strlen(uart_buf), 1000);

