    gyro_x = (int16_t)(rec_data[8] << 8 | rec_data[9]);
    gyro_y = (int16_t)(rec_data[10] << 8 | rec_data[11]);
    gyro_z = (int16_t)(rec_data[12] << 8 | rec_data[13]);

